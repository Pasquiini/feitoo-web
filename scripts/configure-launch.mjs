import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
const production = process.env.VERCEL_ENV
  ? process.env.VERCEL_ENV === 'production'
  : process.env.FEITOO_BUILD_ENV === 'production';
const origin = production
  ? (process.env.FEITOO_PUBLIC_ORIGIN ?? 'https://feitoo.com.br').replace(/\/$/, '')
  : '';
if (origin) {
  const url = new URL(origin);
  if (
    url.protocol !== 'https:' ||
    url.username ||
    url.password ||
    url.pathname !== '/' ||
    url.search ||
    url.hash
  )
    throw new Error('FEITOO_PUBLIC_ORIGIN deve ser uma origem HTTPS, sem caminho ou credenciais.');
}
const contact = process.env.FEITOO_CONTACT_EMAIL ?? 'suporte@feitoo.com.br';
if (contact && !/^[^\s@<>]+@[^\s@<>]+\.[^\s@<>]+$/.test(contact))
  throw new Error('Contato deve ser um e-mail válido.');
const ttlMinutes = Number(process.env.FEITOO_PUBLIC_TTL_MINUTES ?? 120);
if (!Number.isInteger(ttlMinutes) || ttlMinutes < 1 || ttlMinutes > 10080)
  throw new Error('Retenção inválida.');
const launch = {
  origin,
  contact,
  responsible: process.env.FEITOO_RESPONSIBLE_NAME ?? '',
  ga4Id: process.env.FEITOO_GA4_ID ?? '',
  analyticsEnabled: process.env.FEITOO_ANALYTICS_ENABLED === 'true',
  ttlMinutes,
};
if (launch.analyticsEnabled && (!/^G-[A-Z0-9]+$/.test(launch.ga4Id) || !origin))
  throw new Error('Analytics habilitado exige Measurement ID e domínio válidos.');
const target = fileURLToPath(new URL('../src/environments/launch.generated.ts', import.meta.url));
writeFileSync(
  target,
  await format(
    `// Generated by scripts/configure-launch.mjs. Public configuration only.\nexport const launch = ${JSON.stringify(launch, null, 2)};\n`,
    { ...(await resolveConfig(target)), parser: 'typescript' },
  ),
);
writeFileSync(
  fileURLToPath(new URL('../.angular-launch.json', import.meta.url)),
  JSON.stringify(launch),
);
console.log(
  origin
    ? 'Domínio público configurado; revisar checklist antes de publicar.'
    : 'Sem domínio público: build com noindex e robots bloqueado.',
);
